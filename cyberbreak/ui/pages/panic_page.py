from PyQt6.QtWidgets import QAbstractItemView, QWidget, QVBoxLayout, QHBoxLayout, QLabel, QPushButton, QFrame, QGridLayout
from PyQt6.QtGui import QColor
from PyQt6.QtCore import Qt
from cyberbreak.core.isolation import SystemIsolation
from cyberbreak.ui.widgets.nuke_dialog import NukeDialog
from cyberbreak.ui.widgets.status_card import StatusCard
from cyberbreak.ui.widgets.glass import GlassFrame, icon

class PanicPage(QWidget):

    def __init__(self, parent=None):
        super().__init__(parent)
        layout = QVBoxLayout(self)
        layout.setContentsMargins(4, 8, 4, 24)
        layout.setSpacing(22)
        header = QHBoxLayout()
        title_box = QVBoxLayout()
        title_box.setSpacing(8)
        title = QLabel('Emergency controls')
        title.setObjectName('HeaderTitle')
        title.setWordWrap(True)
        subtitle = QLabel('Disconnect the workstation or authorize permanent drive destruction.')
        subtitle.setObjectName('HeaderSubtitle')
        subtitle.setWordWrap(True)
        title_box.addWidget(title)
        title_box.addWidget(subtitle)
        header.addLayout(title_box, 1)
        layout.addLayout(header)
        grid = QGridLayout()
        grid.setSpacing(16)
        self.iso_card = StatusCard('Network isolation', 'Disarmed', 'Disconnect radios and network traffic', 'Standby', 'SECURE')
        grid.addWidget(self.iso_card, 0, 0)
        self.nuke_card = StatusCard('Drive destruction', 'Locked', 'Master passphrase required', 'Armed', 'DANGER')
        grid.addWidget(self.nuke_card, 0, 1)
        layout.addLayout(grid)
        iso_frame = GlassFrame()
        iso_frame.setObjectName('GlassCard')
        i_layout = QVBoxLayout(iso_frame)
        i_layout.setContentsMargins(22, 22, 22, 22)
        i_layout.setSpacing(12)
        i_title = QLabel('Disconnect the workstation')
        i_title.setObjectName('CardTitle')
        i_layout.addWidget(i_title)
        i_desc = QLabel('Disables Wi-Fi, Bluetooth, and WWAN, turns off network interfaces, and drops network traffic. Active browsers, VPNs, Tor, SSH, and messenger processes are terminated.')
        i_desc.setObjectName('HeaderSubtitle')
        i_desc.setWordWrap(True)
        i_desc.setWordWrap(True)
        i_layout.addWidget(i_desc)
        i_btn_row = QHBoxLayout()
        self.isolate_btn = QPushButton('Isolate system')
        self.isolate_btn.setObjectName('PanicButton')
        self.isolate_btn.clicked.connect(self.on_isolate)
        i_btn_row.addWidget(self.isolate_btn)
        i_btn_row.addStretch()
        i_layout.addLayout(i_btn_row)
        layout.addWidget(iso_frame)
        nuke_frame = GlassFrame()
        nuke_frame.setObjectName('GlassCard')
        n_layout = QVBoxLayout(nuke_frame)
        n_layout.setContentsMargins(22, 22, 22, 22)
        n_layout.setSpacing(12)
        n_title = QLabel('Permanent drive destruction')
        n_title.setObjectName('CardTitle')
        n_layout.addWidget(n_title)
        n_desc = QLabel('Destroys encryption headers and partition tables, discards drive blocks, and triggers a kernel crash. A master passphrase is required in the authorization dialog. This permanently destroys affected data.')
        n_desc.setObjectName('HeaderSubtitle')
        n_desc.setWordWrap(True)
        n_desc.setWordWrap(True)
        n_layout.addWidget(n_desc)
        n_btn_row = QHBoxLayout()
        self.nuke_btn = QPushButton('Review drive destruction')
        self.nuke_btn.setObjectName('PanicButton')
        self.nuke_btn.clicked.connect(self.open_nuke_modal)
        n_btn_row.addWidget(self.nuke_btn)
        n_btn_row.addStretch()
        n_layout.addLayout(n_btn_row)
        layout.addWidget(nuke_frame)
        layout.addStretch()

    def on_isolate(self):
        SystemIsolation.trigger_instant_isolation()
        self.iso_card.set_value('System isolated')
        self.iso_card.set_pill('Blackout', 'DANGER')

    def open_nuke_modal(self):
        dlg = NukeDialog(self)
        dlg.exec()
