class ScanWorker(QThread):
    finished_data = pyqtSignal(dict)

    def run(self):
        usb_devs = HardwareManager.get_connected_usb_devices()
        ports = PortAuditor.get_open_listening_ports()
        self.finished_data.emit({'usb': usb_devs, 'ports': ports})

